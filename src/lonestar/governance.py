"""Milestone 10 -- governance: a model card that cannot go stale, and a CI gate.

Two ideas here, both deliberately unglamorous:

1. **The model card is generated, not written.** A hand-written card starts
   accurate and drifts the moment anyone retrains. This one is assembled from the
   artifacts the pipeline actually produced -- the model card JSON, the leakage
   audit, the economics, the drift report, the last retraining cycle -- so every
   number in it is the number that is really in the repo. Regenerate it and it is
   current by construction.

2. **Documentation completeness is a tested requirement.** ``check_artifacts``
   asserts that every governance artifact a reviewer (or an auditor, or the next
   engineer) needs is actually present. It runs in CI, so the docs cannot quietly
   rot while the code moves on.

Run it:  ``python -m lonestar.governance``          (writes docs/model_card.md)
         ``python -m lonestar.governance --check``  (exit 1 if anything is missing)
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

# Everything a reviewer needs to understand, audit, and operate this model.
# (path relative to the repo root, why it has to exist)
REQUIRED_ARTIFACTS: tuple[tuple[str, str], ...] = (
    ("models/model_card.json", "machine-readable model metadata and serving contract"),
    ("models/decision_policy.json", "the thresholds production actually decides with"),
    ("docs/leakage_audit_report.md", "proof the planted leaks were found and removed"),
    ("docs/feature_pipeline.md", "point-in-time feature definitions and guarantees"),
    ("docs/model_results.md", "model selection and honest offline metrics"),
    ("docs/economics_memo.md", "what the decision policy is worth in dollars"),
    ("docs/drift_monitoring.md", "how a regime change is detected without labels"),
    ("docs/retraining.md", "the last challenger/champion cycle and its verdict"),
    ("docs/runbook.md", "what a human does when the monitor alerts"),
    ("docs/decisions", "architecture decision records"),
)

# Optional: present after a full pipeline run, absent on a fresh clone.
GENERATED_REPORTS: tuple[str, ...] = (
    "reports/leakage_audit.json",
    "reports/drift_report.json",
    "reports/retraining_cycle.json",
)


@dataclass
class ArtifactCheck:
    present: list[str]
    missing: list[tuple[str, str]]

    @property
    def ok(self) -> bool:
        return not self.missing


def check_artifacts(root: Path | str = ".") -> ArtifactCheck:
    """Verify every required governance artifact exists."""
    root = Path(root)
    present: list[str] = []
    missing: list[tuple[str, str]] = []
    for rel, why in REQUIRED_ARTIFACTS:
        (present.append(rel) if (root / rel).exists() else missing.append((rel, why)))
    return ArtifactCheck(present=present, missing=missing)


def _load(path: Path) -> dict | None:
    """Read a JSON artifact, or return None if this stage has not been run."""
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def gather(root: Path | str = ".") -> dict:
    """Collect every artifact the model card is assembled from."""
    root = Path(root)
    return {
        "card": _load(root / "models/model_card.json"),
        "policy": _load(root / "models/decision_policy.json"),
        "audit": _load(root / "reports/leakage_audit.json"),
        "drift": _load(root / "reports/drift_report.json"),
        "retraining": _load(root / "reports/retraining_cycle.json"),
    }


def _fmt(value, spec: str = "", fallback: str = "_not yet generated_") -> str:
    """Format a value, degrading gracefully when a stage has not been run."""
    if value is None:
        return fallback
    return format(value, spec) if spec else str(value)


