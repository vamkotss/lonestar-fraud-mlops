def main() -> None:
    ap = argparse.ArgumentParser(description="Generate the model card / check artifacts (M10).")
    ap.add_argument("--root", default=".", help="Repository root.")
    ap.add_argument("--out", default="docs/model_card.md")
    ap.add_argument(
        "--check",
        action="store_true",
        help="Only verify governance artifacts exist; exit 1 if any are missing.",
    )
    args = ap.parse_args()

    root = Path(args.root)
    result = check_artifacts(root)

    if args.check:
        for rel in result.present:
            print(f"  ok      {rel}")
        for rel, why in result.missing:
            print(f"  MISSING {rel}  -- {why}")
        if not result.ok:
            print(f"\n{len(result.missing)} governance artifact(s) missing.")
            sys.exit(1)
        print(f"\nAll {len(result.present)} governance artifacts present.")
        return

    out = root / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_model_card(gather(root)), encoding="utf-8")
    print(f"Wrote {out}")
    if result.missing:
        print(f"note: {len(result.missing)} governance artifact(s) still missing:")
        for rel, _ in result.missing:
            print(f"  - {rel}")


if __name__ == "__main__":
    main()
